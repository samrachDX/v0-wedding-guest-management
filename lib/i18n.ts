export const translations: Record<Language, Record<TranslationKey, string>> = { en, km }

export function translate(language: Language, key: TranslationKey, vars?: Record<string, string | number>) {
  let text = translations[language][key] ?? translations.en[key] ?? key
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      text = text.replaceAll(`{${name}}`, String(value))
    }
  }
  return text
}

/** Labels used for stored enum values ("Groom Side", "money", "Cash", ...). */
export function guestSideLabel(language: Language, guestType: string) {
  return translate(language, guestType === "Groom Side" ? "side.groom" : "side.bride")
}

export function giftTypeLabel(language: Language, type: string) {
  return translate(language, type === "money" ? "gifts.money" : "gifts.item")
}

export function paymentMethodLabel(language: Language, method?: string) {
  if (!method) return ""
  return method === "Cash" ? translate(language, "gifts.cash") : method
}
